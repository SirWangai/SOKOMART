
CREATE TABLE sokomart.products (
	product_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	product_name varchar(150) NOT NULL,
	category varchar(40) NOT NULL,
	brand varchar(60) NULL,
	unit_price numeric(12, 2) NOT NULL,
	cost_price numeric(12, 2) NOT NULL,
	stock_quantity int4 DEFAULT 0 NOT NULL,
	created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	product_status varchar(15) DEFAULT 'active'::character varying NOT NULL,
	CONSTRAINT chk_products_category CHECK (((category)::text = ANY ((ARRAY['Electronics'::character varying, 'Groceries'::character varying, 'Fashion'::character varying, 'Home Appliances'::character varying, 'Beauty'::character varying])::text[]))),
	CONSTRAINT chk_products_cost CHECK ((cost_price >= (0)::numeric)),
	CONSTRAINT chk_products_price CHECK ((unit_price > (0)::numeric)),
	CONSTRAINT chk_products_status CHECK (((product_status)::text = ANY ((ARRAY['active'::character varying, 'discontinued'::character varying, 'out_of_stock'::character varying])::text[]))),
	CONSTRAINT chk_products_stock CHECK ((stock_quantity >= 0)),
	CONSTRAINT products_category_not_null NOT NULL category,
	CONSTRAINT products_cost_price_not_null NOT NULL cost_price,
	CONSTRAINT products_created_at_not_null NOT NULL created_at,
	CONSTRAINT products_pkey PRIMARY KEY (product_id),
	CONSTRAINT products_product_id_not_null NOT NULL product_id,
	CONSTRAINT products_product_name_key UNIQUE (product_name),
	CONSTRAINT products_product_name_not_null NOT NULL product_name,
	CONSTRAINT products_product_status_not_null NOT NULL product_status,
	CONSTRAINT products_stock_quantity_not_null NOT NULL stock_quantity,
	CONSTRAINT products_unit_price_not_null NOT NULL unit_price
);