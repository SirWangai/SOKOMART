

CREATE TABLE sokomart.product_price_history (
	price_history_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	product_id int4 NOT NULL,
	old_price numeric(12, 2) NOT NULL,
	new_price numeric(12, 2) NOT NULL,
	change_reason varchar(200) NULL,
	changed_by varchar(63) DEFAULT CURRENT_USER NOT NULL,
	changed_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	CONSTRAINT chk_price_history_prices CHECK (((old_price > (0)::numeric) AND (new_price > (0)::numeric))),
	CONSTRAINT product_price_history_changed_at_not_null NOT NULL changed_at,
	CONSTRAINT product_price_history_changed_by_not_null NOT NULL changed_by,
	CONSTRAINT product_price_history_new_price_not_null NOT NULL new_price,
	CONSTRAINT product_price_history_old_price_not_null NOT NULL old_price,
	CONSTRAINT product_price_history_pkey PRIMARY KEY (price_history_id),
	CONSTRAINT product_price_history_price_history_id_not_null NOT NULL price_history_id,
	CONSTRAINT product_price_history_product_id_not_null NOT NULL product_id
);


-- sokomart.product_price_history foreign keys

ALTER TABLE sokomart.product_price_history ADD CONSTRAINT product_price_history_product_id_fkey FOREIGN KEY (product_id) REFERENCES sokomart.products(product_id);