
CREATE TABLE sokomart.payments (
	payment_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	order_id int4 NOT NULL,
	payment_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	payment_method varchar(20) NOT NULL,
	amount numeric(12, 2) NOT NULL,
	payment_status varchar(12) DEFAULT 'pending'::character varying NOT NULL,
	transaction_reference varchar(30) NULL,
	CONSTRAINT chk_payments_amount CHECK ((amount > (0)::numeric)),
	CONSTRAINT chk_payments_method CHECK (((payment_method)::text = ANY ((ARRAY['M-Pesa'::character varying, 'card'::character varying, 'bank transfer'::character varying, 'cash on delivery'::character varying])::text[]))),
	CONSTRAINT chk_payments_status CHECK (((payment_status)::text = ANY ((ARRAY['successful'::character varying, 'failed'::character varying, 'pending'::character varying])::text[]))),
	CONSTRAINT payments_amount_not_null NOT NULL amount,
	CONSTRAINT payments_order_id_not_null NOT NULL order_id,
	CONSTRAINT payments_payment_date_not_null NOT NULL payment_date,
	CONSTRAINT payments_payment_id_not_null NOT NULL payment_id,
	CONSTRAINT payments_payment_method_not_null NOT NULL payment_method,
	CONSTRAINT payments_payment_status_not_null NOT NULL payment_status,
	CONSTRAINT payments_pkey PRIMARY KEY (payment_id),
	CONSTRAINT payments_transaction_reference_key UNIQUE (transaction_reference)
);


-- sokomart.payments foreign keys

ALTER TABLE sokomart.payments ADD CONSTRAINT payments_order_id_fkey FOREIGN KEY (order_id) REFERENCES sokomart.orders(order_id) ON DELETE CASCADE;