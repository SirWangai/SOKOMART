
CREATE TABLE sokomart.order_items (
	order_item_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	order_id int4 NOT NULL,
	product_id int4 NOT NULL,
	quantity int4 NOT NULL,
	unit_price numeric(12, 2) NOT NULL,
	discount_percentage numeric(5, 2) DEFAULT 0 NOT NULL,
	line_total numeric(12, 2) NOT NULL,
	CONSTRAINT chk_items_discount CHECK (((discount_percentage >= (0)::numeric) AND (discount_percentage <= (100)::numeric))),
	CONSTRAINT chk_items_line_total CHECK ((line_total = round((((quantity)::numeric * unit_price) * ((1)::numeric - (discount_percentage / (100)::numeric))), 2))),
	CONSTRAINT chk_items_price CHECK ((unit_price > (0)::numeric)),
	CONSTRAINT chk_items_quantity CHECK ((quantity > 0)),
	CONSTRAINT order_items_discount_percentage_not_null NOT NULL discount_percentage,
	CONSTRAINT order_items_line_total_not_null NOT NULL line_total,
	CONSTRAINT order_items_order_id_not_null NOT NULL order_id,
	CONSTRAINT order_items_order_item_id_not_null NOT NULL order_item_id,
	CONSTRAINT order_items_pkey PRIMARY KEY (order_item_id),
	CONSTRAINT order_items_product_id_not_null NOT NULL product_id,
	CONSTRAINT order_items_quantity_not_null NOT NULL quantity,
	CONSTRAINT order_items_unit_price_not_null NOT NULL unit_price,
	CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id)
);


-- sokomart.order_items foreign keys

ALTER TABLE sokomart.order_items ADD CONSTRAINT order_items_order_id_fkey FOREIGN KEY (order_id) REFERENCES sokomart.orders(order_id) ON DELETE CASCADE;
ALTER TABLE sokomart.order_items ADD CONSTRAINT order_items_product_id_fkey FOREIGN KEY (product_id) REFERENCES sokomart.products(product_id);