
CREATE TABLE sokomart.payment_staging (
	staging_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	payment_id int4 NOT NULL,
	order_id int4 NOT NULL,
	payment_date timestamp NOT NULL,
	payment_method varchar(20) NOT NULL,
	amount numeric(12, 2) NOT NULL,
	payment_status varchar(12) NOT NULL,
	transaction_reference varchar(30) NULL,
	source_file varchar(80) NOT NULL,
	loaded_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	CONSTRAINT payment_staging_amount_not_null NOT NULL amount,
	CONSTRAINT payment_staging_loaded_at_not_null NOT NULL loaded_at,
	CONSTRAINT payment_staging_order_id_not_null NOT NULL order_id,
	CONSTRAINT payment_staging_payment_date_not_null NOT NULL payment_date,
	CONSTRAINT payment_staging_payment_id_not_null NOT NULL payment_id,
	CONSTRAINT payment_staging_payment_method_not_null NOT NULL payment_method,
	CONSTRAINT payment_staging_payment_status_not_null NOT NULL payment_status,
	CONSTRAINT payment_staging_pkey PRIMARY KEY (staging_id),
	CONSTRAINT payment_staging_source_file_not_null NOT NULL source_file,
	CONSTRAINT payment_staging_staging_id_not_null NOT NULL staging_id
);