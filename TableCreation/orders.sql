
CREATE TABLE sokomart.orders (
	order_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	customer_id int4 NOT NULL,
	order_date timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	order_status varchar(12) DEFAULT 'pending'::character varying NOT NULL,
	shipping_county varchar(40) NOT NULL,
	delivery_fee numeric(12, 2) DEFAULT 0 NOT NULL,
	total_amount numeric(12, 2) DEFAULT 0 NOT NULL,
	CONSTRAINT chk_orders_delivery CHECK ((delivery_fee >= (0)::numeric)),
	CONSTRAINT chk_orders_status CHECK (((order_status)::text = ANY ((ARRAY['completed'::character varying, 'pending'::character varying, 'cancelled'::character varying, 'returned'::character varying])::text[]))),
	CONSTRAINT chk_orders_total CHECK ((total_amount >= (0)::numeric)),
	CONSTRAINT orders_customer_id_not_null NOT NULL customer_id,
	CONSTRAINT orders_delivery_fee_not_null NOT NULL delivery_fee,
	CONSTRAINT orders_order_date_not_null NOT NULL order_date,
	CONSTRAINT orders_order_id_not_null NOT NULL order_id,
	CONSTRAINT orders_order_status_not_null NOT NULL order_status,
	CONSTRAINT orders_pkey PRIMARY KEY (order_id),
	CONSTRAINT orders_shipping_county_not_null NOT NULL shipping_county,
	CONSTRAINT orders_total_amount_not_null NOT NULL total_amount
);


-- sokomart.orders foreign keys

ALTER TABLE sokomart.orders ADD CONSTRAINT orders_customer_id_fkey FOREIGN KEY (customer_id) REFERENCES sokomart.customers(customer_id);