
CREATE TABLE sokomart.customers (
	customer_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	first_name varchar(60) NOT NULL,
	last_name varchar(60) NOT NULL,
	email varchar(150) NOT NULL,
	phone_number varchar(20) NULL,
	county varchar(40) NOT NULL,
	registration_date date DEFAULT CURRENT_DATE NOT NULL,
	customer_status varchar(12) DEFAULT 'active'::character varying NOT NULL,
	CONSTRAINT chk_customers_phone CHECK (((phone_number IS NULL) OR ((phone_number)::text ~ '^07[0-9]{2} [0-9]{3} [0-9]{3}$'::text))),
	CONSTRAINT chk_customers_status CHECK (((customer_status)::text = ANY ((ARRAY['active'::character varying, 'inactive'::character varying, 'suspended'::character varying])::text[]))),
	CONSTRAINT customers_county_not_null NOT NULL county,
	CONSTRAINT customers_customer_id_not_null NOT NULL customer_id,
	CONSTRAINT customers_customer_status_not_null NOT NULL customer_status,
	CONSTRAINT customers_email_key UNIQUE (email),
	CONSTRAINT customers_email_not_null NOT NULL email,
	CONSTRAINT customers_first_name_not_null NOT NULL first_name,
	CONSTRAINT customers_last_name_not_null NOT NULL last_name,
	CONSTRAINT customers_pkey PRIMARY KEY (customer_id),
	CONSTRAINT customers_registration_date_not_null NOT NULL registration_date
);